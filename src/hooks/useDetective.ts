'use client';

import { useState, useEffect, useCallback, useRef } from 'react';
import useStore from '@/store/useStore';
import useDetectiveStore from '@/store/detectiveStore';
import type { DetectiveMessage } from '@/types/detective';

export function useDetective(boardId: string) {
  const { nodes, edges, boardTitle } = useStore();
  const store = useDetectiveStore();

  const [input, setInput] = useState('');
  const [messages, setMessages] = useState<DetectiveMessage[]>([]);
  const [isStreaming, setIsStreaming] = useState(false);
  const [isLoadingHistory, setIsLoadingHistory] = useState(false);
  const [sessionId, setSessionId] = useState<string | null>(null);
  const sessionIdRef = useRef<string | null>(null);

  useEffect(() => {
    sessionIdRef.current = sessionId;
  }, [sessionId]);

  // Load session history when boardId changes
  useEffect(() => {
    if (!boardId) return;

    let isMounted = true;
    const fetchSessionHistory = async () => {
      setIsLoadingHistory(true);
      try {
        const res = await fetch(`/api/detective/sessions?boardId=${boardId}`);
        if (res.ok) {
          const data = await res.json();
          if (isMounted) {
            if (data.sessions && data.sessions.length > 0) {
              const latest = data.sessions[0];
              const loadedMsgs = (latest.messages || []) as DetectiveMessage[];
              setSessionId(latest.id);
              store.setSessionId(latest.id);
              setMessages(loadedMsgs);
              store.setMessages(loadedMsgs);
            } else {
              setSessionId(null);
              store.setSessionId(null);
              setMessages([]);
              store.setMessages([]);
            }
          }
        }
      } catch (err) {
        console.error('Failed to load detective session history:', err);
      } finally {
        if (isMounted) {
          setIsLoadingHistory(false);
        }
      }
    };

    fetchSessionHistory();

    return () => {
      isMounted = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [boardId]);

  useEffect(() => {
    const fetchConfig = async () => {
      store.setConfigLoading(true);
      try {
        const res = await fetch('/api/detective/config');
        if (res.ok) {
          const data = await res.json();
          if (data.config) {
            store.setAIConfig(data.config);
            store.setConfigured(true);
          } else {
            store.setConfigured(false);
          }
        } else {
          store.setConfigured(false);
        }
      } catch (err) {
        console.error('Failed to fetch AI config:', err);
        store.setConfigured(false);
      } finally {
        store.setConfigLoading(false);
      }
    };
    fetchConfig();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  const sendMessage = useCallback(async (text: string) => {
    if (!text.trim() || isStreaming) return;

    const userMsg: DetectiveMessage = {
      id: `user-${Date.now()}`,
      role: 'user',
      content: text,
      timestamp: Date.now(),
    };

    const newMessages = [...messages, userMsg];
    setMessages(newMessages);
    store.addMessage(userMsg);
    setInput('');
    setIsStreaming(true);

    const assistantMsgId = `assistant-${Date.now()}`;
    const assistantMsg: DetectiveMessage = {
      id: assistantMsgId,
      role: 'assistant',
      content: '',
      timestamp: Date.now(),
    };

    setMessages([...newMessages, assistantMsg]);

    try {
      const response = await fetch('/api/detective/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          boardId,
          boardTitle,
          nodes,
          edges,
          messages: newMessages
            .filter((m) => m.content && m.content.trim())
            .map((m) => ({
              role: m.role,
              content: m.content,
            })),
        }),
      });

      if (!response.ok) {
        const errData = await response.json().catch(() => ({ error: 'Failed to communicate with detective' }));
        throw new Error(errData.error || 'Chat request failed');
      }

      if (response.body) {
        const reader = response.body.getReader();
        const decoder = new TextDecoder();
        let accumulatedContent = '';

        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          const chunk = decoder.decode(value, { stream: true });
          accumulatedContent += chunk;

          setMessages((prev) =>
            prev.map((msg) =>
              msg.id === assistantMsgId ? { ...msg, content: accumulatedContent } : msg
            )
          );
        }

        if (!accumulatedContent.trim()) {
          throw new Error('No response was generated by the AI model. Please check that your model name and API key are valid in the Config tab.');
        }

        const finalAssistantMsg: DetectiveMessage = {
          ...assistantMsg,
          content: accumulatedContent,
        };
        const updatedMessages = [...newMessages, finalAssistantMsg];
        store.addMessage(finalAssistantMsg);

        // Persist session to Turso database
        try {
          const saveRes = await fetch('/api/detective/sessions', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              boardId,
              sessionId: sessionIdRef.current || undefined,
              messages: updatedMessages,
              boardSnapshot: {
                boardTitle,
                nodeCount: nodes.length,
                edgeCount: edges.length,
              },
            }),
          });
          if (saveRes.ok) {
            const saveData = await saveRes.json();
            if (saveData.session?.id) {
              setSessionId(saveData.session.id);
              store.setSessionId(saveData.session.id);
            }
          }
        } catch (saveErr) {
          console.error('Failed to auto-save detective session:', saveErr);
        }
      }
    } catch (error) {
      console.error('Streaming chat error:', error);
      const errorMsg: DetectiveMessage = {
        ...assistantMsg,
        content: `Error: ${error instanceof Error ? error.message : 'Unable to connect with the Detective.'}`,
      };
      setMessages((prev) =>
        prev.map((msg) => (msg.id === assistantMsgId ? errorMsg : msg))
      );
      store.addMessage(errorMsg);
    } finally {
      setIsStreaming(false);
    }
  }, [messages, isStreaming, boardId, boardTitle, nodes, edges, store]);

  const clearChat = useCallback(async () => {
    if (isStreaming) return;
    setMessages([]);
    store.clearConversation();
    const currentId = sessionIdRef.current;
    setSessionId(null);
    store.setSessionId(null);

    if (currentId) {
      try {
        await fetch(`/api/detective/sessions?sessionId=${currentId}`, {
          method: 'DELETE',
        });
      } catch (err) {
        console.error('Failed to delete detective session:', err);
      }
    } else if (boardId) {
      try {
        await fetch(`/api/detective/sessions?boardId=${boardId}`, {
          method: 'DELETE',
        });
      } catch (err) {
        console.error('Failed to delete detective session for board:', err);
      }
    }
  }, [isStreaming, store, boardId]);

  const handleInputChange = (e: React.ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) => {
    setInput(e.target.value);
  };

  const handleSubmit = (e?: React.FormEvent) => {
    if (e) e.preventDefault();
    if (input.trim()) {
      sendMessage(input);
    }
  };

  const runAnalysis = async (type: string = 'full_scan') => {
    store.setAnalyzing(true);
    try {
      const res = await fetch('/api/detective/analyze', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ boardId, boardTitle, nodes, edges, type }),
      });
      if (res.ok) {
        const data = await res.json();
        store.setAnalysis(data);
      }
    } catch (err) {
      console.error('Failed to run analysis:', err);
    } finally {
      store.setAnalyzing(false);
    }
  };

  return {
    isConfigured: store.isConfigured,
    messages,
    input,
    handleInputChange,
    handleSubmit,
    isStreaming,
    isLoadingHistory,
    analysis: store.lastAnalysis,
    isAnalyzing: store.isAnalyzing,
    runAnalysis,
    sendMessage,
    setMessages,
    clearChat,
  };
}

